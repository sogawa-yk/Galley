def zip_terraform_dir(terraform_dir: str) -> str:
    """Zip a Terraform directory for Resource Manager upload.

    Args:
        terraform_dir: Path to directory containing .tf files.

    Returns:
        Path to the created zip file.

    Raises:
        FileNotFoundError: If terraform_dir does not exist.
        ValueError: If no .tf files found.
    """
    tf_path = Path(terraform_dir)
    if not tf_path.is_dir():
        raise FileNotFoundError(f"Terraform directory not found: {terraform_dir}")

    tf_files = list(tf_path.glob("*.tf")) + list(tf_path.glob("*.tfvars"))
    sh_files = list(tf_path.glob("*.sh"))
    all_files = tf_files + sh_files

    if not tf_files:
        raise ValueError(f"No .tf files found in {terraform_dir}")

    zip_path = str(tf_path.parent / "terraform.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in all_files:
            zf.write(f, f.name)  # Flat structure (no subdirs)

    return zip_path


def create_stack(
    compartment_id: str,
    terraform_dir: str,
    display_name: str,
    terraform_version: str = "1.5.x",
) -> str:
    """Create a Resource Manager Stack from a Terraform directory.

    Zips the directory and uploads it. If a stack with the same name
    already exists, updates it instead.

    Args:
        compartment_id: Compartment OCID.
        terraform_dir: Path to Terraform directory.
        display_name: Stack display name.
        terraform_version: Terraform version constraint.

    Returns:
        Stack OCID.
    """
    zip_path = zip_terraform_dir(terraform_dir)

    # Check for existing stack with same name
    existing = _find_stack_by_name(compartment_id, display_name)
    if existing:
        _update_stack(existing, zip_path)
        return existing

    result = run_command([
        "resource-manager", "stack", "create",
        "--compartment-id", compartment_id,
        "--config-source", zip_path,
        "--display-name", display_name,
        "--description", "Auto-generated by OCI Demo Builder",
        "--terraform-version", terraform_version,
    ])
    return result["data"]["id"]


def _find_stack_by_name(compartment_id: str, display_name: str) -> str | None:
    """Find an existing stack by display name.

    Returns:
        Stack OCID if found, None otherwise.
    """
    try:
        result = run_command([
            "resource-manager", "stack", "list",
            "--compartment-id", compartment_id,
            "--display-name", display_name,
        ])
        stacks = result.get("data", [])
        for stack in stacks:
            if stack.get("lifecycle-state") == "ACTIVE":
                return stack["id"]
    except Exception:
        pass
    return None


def _update_stack(stack_id: str, zip_path: str) -> None:
    """Update an existing stack with new Terraform config."""
    run_command([
        "resource-manager", "stack", "update",
        "--stack-id", stack_id,
        "--config-source", zip_path,
        "--force",
    ])


