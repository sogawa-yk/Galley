def get_stack_outputs(stack_id: str, job_id: str) -> dict:
    """Get Terraform outputs from a completed Apply job.

    Attempts to retrieve outputs using the following strategies:
    1. Primary: Get terraform.tfstate via get-job-tf-state and extract outputs
    2. Fallback: Parse outputs from job logs

    Args:
        stack_id: Stack OCID.
        job_id: Apply Job OCID.

    Returns:
        Dict of Terraform output values.
    """
    # Strategy 1: Get outputs from terraform.tfstate
    try:
        result = run_command([
            "resource-manager", "job", "get-job-tf-state",
            "--job-id", job_id,
        ])
        # The response may be base64-encoded or raw JSON
        tf_state_data = result.get("data", result)
        if isinstance(tf_state_data, str):
            try:
                tf_state_data = json.loads(base64.b64decode(tf_state_data))
            except Exception:
                tf_state_data = json.loads(tf_state_data)
        outputs = {}
        raw_outputs = tf_state_data.get("outputs", {})
        for key, val in raw_outputs.items():
            outputs[key] = val.get("value", val)
        if outputs:
            return outputs
    except Exception:
        logger.debug("Failed to get outputs from tf-state, falling back to log parsing")

    # Strategy 2 (Fallback): Parse outputs from job logs
    try:
        output_result = run_command([
            "resource-manager", "job", "get-job-logs",
            "--job-id", job_id,
        ])
        outputs = _parse_outputs_from_logs(output_result)
        if outputs:
            return outputs
    except Exception:
        logger.debug("Failed to get outputs from job logs")

    logger.warning(
        "Could not retrieve stack outputs for job %s. "
        "Both tf-state and log parsing methods returned empty results.",
        job_id,
    )
    return {}


def _parse_outputs_from_logs(log_data: dict) -> dict:
    """Parse Terraform outputs from job log data.

    Returns:
        Dict of output key-value pairs.
    """
    outputs = {}
    items = log_data.get("data", [])
    capture = False
    for item in items:
        message = item.get("message", "")
        if "Outputs:" in message:
            capture = True
            continue
        if capture and "=" in message:
            parts = message.split("=", 1)
            key = parts[0].strip()
            value = parts[1].strip().strip('"')
            outputs[key] = value
    return outputs


def save_stack_outputs(
    outputs: dict,
    stack_id: str,
    job_id: str,
    project_name: str,
    output_path: str,
) -> str:
    """Save stack outputs to JSON file with metadata.

    Args:
        outputs: Terraform output values.
        stack_id: Stack OCID.
        job_id: Apply Job OCID.
        project_name: Project name.
        output_path: Path to write JSON file.

    Returns:
        Path to the output file.
    """
    data = {
        **outputs,
        "_stack_id": stack_id,
        "_apply_job_id": job_id,
        "_project_name": project_name,
    }
    with open(output_path, "w") as f:
        json.dump(data, f, indent=2)
    return output_path
