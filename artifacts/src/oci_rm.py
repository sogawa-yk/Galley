def get_job_status(job_id: str) -> dict:
    """Get the status of a job.

    Args:
        job_id: Job OCID.

    Returns:
        Dict with job details including lifecycle_state.
    """
    result = run_command([
        "resource-manager", "job", "get",
        "--job-id", job_id,
    ])
    data = result["data"]
    return {
        "id": data["id"],
        "operation": data["operation"],
        "lifecycle_state": data["lifecycle-state"],
        "time_created": data.get("time-created"),
        "time_finished": data.get("time-finished"),
    }


def wait_for_job(
    job_id: str,
    timeout: int = 3600,
    interval: int = 30,
) -> dict:
    """Poll a job until completion or timeout.

    Args:
        job_id: Job OCID.
        timeout: Maximum wait time in seconds (default 3600 = 60 min).
        interval: Polling interval in seconds (default 30).

    Returns:
        Final job status dict.

    Raises:
        TimeoutError: If job does not complete within timeout.
    """
    start = time.time()
    while True:
        status = get_job_status(job_id)
        state = status["lifecycle_state"]

        if state in ("SUCCEEDED", "FAILED", "CANCELED"):
            return status

        elapsed = time.time() - start
        if elapsed >= timeout:
            raise TimeoutError(
                f"Job {job_id} timed out after {timeout}s. "
                f"Current state: {state}"
            )

        time.sleep(interval)


